/**
 * Builds docs/ASSETS.md from the live registries so the list can never drift from the game.
 * Pure aside from reading the repo's public folder and render sources (Node only; used by the script and its test).
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CHARACTERS } from './characters';
import { ENEMIES } from './enemies';
import { ALLIES, DISCOVERIES, HUB_ROOMS, UPGRADES } from './progression';
import { AREAS } from './areas';
import { WEAPONS } from './weapons';
import { EVOLUTIONS } from './evolutions';
import { PASSIVES } from './passives';
import { LOKPET_VARIANTS } from './lokPets';
import { AMBIENT_KINDS } from './ambient';
import { HATS } from './hats';
import { CELEBRATIONS } from './celebrations';
import { THEMED_PALETTES } from './themedPalettes';
import { FACTIONS } from './factions';
import { CARD_MANIFESTS } from './cards';
import { LOK_GLYPH_PATHS } from '../../ui/lokGlyphs.generated';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');

type Row = Record<string, unknown>;
const cell = (v: unknown): string => String(v ?? '').replace(/\|/g, '/').replace(/\s+/g, ' ').trim();

function table(headers: string[], rows: unknown[][]): string {
  return [`| ${headers.join(' | ')} |`, `| ${headers.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
}

function files(dir: string, filter: (n: string) => boolean = () => true): string[] {
  try {
    return readdirSync(path.join(root, dir)).filter((n) => filter(n) && statSync(path.join(root, dir, n)).isFile()).sort();
  } catch { return []; }
}

/** First comment line of a source file: what the module draws. */
function purpose(file: string): string {
  const text = readFileSync(file, 'utf8').split('\n').slice(0, 25);
  for (const raw of text) {
    const line = raw.trim().replace(/^\/\*\*?\s?|^\*\s?|^\/\/\s?|\*\/$/g, '').trim();
    if (line.length > 12 && !/^(import|export|const|let|type|interface|function|@)/.test(line)) return line.slice(0, 140);
  }
  return '';
}

function sfxCueIds(): string[] {
  const src = readFileSync(path.join(root, 'src/game/audio/sfxCues.ts'), 'utf8');
  const m = src.match(/export type SfxCueId =([\s\S]*?);/);
  return m ? [...m[1]!.matchAll(/'([A-Za-z0-9]+)'/g)].map((x) => x[1]!) : [];
}

function section(title: string, intro: string, body: string): string {
  return `## ${title}\n\n${intro}\n\n${body}\n`;
}

export function buildAssetCatalog(): string {
  const out: string[] = [];
  out.push(`# 616 Survivor: asset catalog

Generated by \`artifacts/survivor-616/scripts/export-asset-catalog.ts\` from the live registries. Do not edit by hand:
run \`pnpm exec tsx scripts/export-asset-catalog.ts ../../docs/ASSETS.md\` from \`artifacts/survivor-616/\`. A test fails when this file is stale.

Almost every picture in the game is **drawn in code** (procedural rigs, Canvas2D, Lok glyph paths), so this catalog lists records and the modules that draw them, not image files. The few real picture and sound files are listed at the end.

Back to the [docs index](./README.md).

## Jump to
${['Counts', 'Objective and world art (rescue cage, dungeon doors, chest)', 'Characters', 'Enemies', 'Factions', 'Allies', 'Areas', 'Weapons', 'Evolutions', 'Passives', 'Upgrades', 'LokPets', 'Ambient life', 'Hats', 'Celebrations', 'Themed palettes', 'Cards', 'Hub rooms and discoveries', 'Lok glyph icons', 'Sound cues', 'Music', 'Pictures and public files', 'Renderer and art modules']
    .map((t) => `- [${t}](#${t.toLowerCase().replace(/[^a-z0-9 ]/g, '').trim().replace(/ +/g, '-')})`).join('\n')}
`);

  const glyphKeys = Object.keys(LOK_GLYPH_PATHS).sort();
  const cues = sfxCueIds();
  out.push(section('Counts', 'How much of each there is right now.', table(['Kind', 'Count'], [
    ['Characters', String(CHARACTERS.length)], ['Enemies', String(ENEMIES.length)], ['Factions', String(FACTIONS.length)], ['Allies', String(ALLIES.length)],
    ['Areas', String(AREAS.length)], ['Weapons', String(WEAPONS.length)], ['Evolutions', String(EVOLUTIONS.length)], ['Passives', String(PASSIVES.length)],
    ['Level-up upgrades', String(UPGRADES.length)], ['LokPets', String(LOKPET_VARIANTS.length)], ['Ambient kinds', String(AMBIENT_KINDS.length)],
    ['Hats', String(HATS.length)], ['Celebrations', String(CELEBRATIONS.length)], ['Themed palettes', String(THEMED_PALETTES.length)],
    ['Cards', String(CARD_MANIFESTS.length)], ['Lok glyph icons', String(glyphKeys.length)], ['Sound cues', String(cues.length)],
  ])));

  out.push(section('Objective and world art (rescue cage, dungeon doors, chest)',
    'The pieces that tell the player what to do next. All procedural, all animated from the run clock.',
    table(['Piece', 'Drawn by', 'What it shows'], [
      ['Rescue cage', 'src/game/render/rescueArt.ts `drawRescue`', 'Iron cage with the real ally inside, light beacon, rattle when you are near, quarter pips, dust, strobe, bars bowing open'],
      ['Rescue burst', 'src/game/render/rescueArt.ts `drawBurst`', 'Bars fly apart, shock ring, ground cracks, confetti, light pillar, the survivor hops out'],
      ['Rescue pointer and screen fx', 'src/game/render/rescueArt.ts `drawRescuePointer`', 'Edge arrow toward an off-screen cage, colour wash while freeing, white flash on release'],
      ['Dungeon doorway', 'src/game/render/objectiveArt.ts `drawDungeonEntrances`', 'Stone arch, steps going down, flickering torches, rising motes'],
      ['Way-out door', 'src/game/render/objectiveArt.ts `drawDungeonExit`', 'Light spill and chevrons running toward the exit'],
      ['Treasure chest', 'src/game/render/objectiveArt.ts `drawDungeonChest`', 'Locked (chains, latch), unlocked (gold glow, sparkles, breathing lid), opened (lid up, light pouring out)'],
    ])));

  out.push(section('Characters', 'Playable survivors. Each is a procedural rig plus a palette (`src/game/data/characters.ts`, rigs from `src/game/sprites/rigs.ts`).',
    table(['Id', 'Name', 'Handle', 'Weapon', 'Rarity'], CHARACTERS.map((c) => [c.id, c.name, c.handle, c.weapon?.name ?? c.weapon?.id, (c as unknown as Row).rarity ?? '']))));
  out.push(section('Enemies', 'Everything that attacks you (`src/game/data/enemies.ts`). Behavior picks movement, traits add teleport, ghost or shift.',
    table(['Id', 'Name', 'Faction', 'Behavior'], ENEMIES.map((e) => [e.id, e.name, (e as unknown as Row).faction, (e as unknown as Row).behavior]))));
  out.push(section('Factions', 'Named enemy rosters (`src/game/data/factions.ts`).',
    table(['Id', 'Name', 'Roster size'], FACTIONS.map((f) => [(f as unknown as Row).id, (f as unknown as Row).name ?? (f as unknown as Row).id, ((f as unknown as Row).roster as unknown[] | undefined)?.length ?? ''] ))));
  out.push(section('Allies', 'Survivors you rescue from the cage (`src/game/data/progression.ts`). Each one is also a rig, drawn inside the rescue cage.',
    table(['Id', 'Name', 'Role', 'Hub room', 'Silhouette hint', 'Glow'], ALLIES.map((a) => [a.id, a.name, a.role, a.room, a.rigHint ?? '', a.palette.glow]))));
  out.push(section('Areas', 'Maps (`src/game/data/areas*.ts`). Backdrop is the menu reference picture, the arena itself is drawn in code.',
    table(['Id', 'Name', 'District', 'Rescue ally', 'Backdrop'], AREAS.map((a) => [a.id, a.name, a.district, a.rescueAllyId ?? '', a.backdrop]))));
  out.push(section('Weapons', '`src/game/data/weapons.ts`.', table(['Id', 'Name'], WEAPONS.map((w) => [w.id, w.name]))));
  out.push(section('Evolutions', '`src/game/data/evolutions.ts`.', table(['Id', 'Name'], EVOLUTIONS.map((e) => [e.id, (e as unknown as Row).name ?? e.id]))));
  out.push(section('Passives', '`src/game/data/passives.ts`.', table(['Id', 'Name'], PASSIVES.map((p) => [p.id, (p as unknown as Row).name ?? p.id]))));
  out.push(section('Upgrades', 'Level-up choices (`src/game/data/progression.ts`).', table(['Id', 'Name'], UPGRADES.map((u) => [u.id, (u as unknown as Row).name ?? u.id]))));
  out.push(section('LokPets', '`src/game/data/lokPets.ts`.', table(['Id', 'Name'], LOKPET_VARIANTS.map((p) => [p.id, (p as unknown as Row).name ?? p.id]))));
  out.push(section('Ambient life', 'Non-combat background actors (`src/game/data/ambient.ts`).', table(['Id', 'Name'], AMBIENT_KINDS.map((a) => [a.id, (a as unknown as Row).name ?? a.id]))));
  out.push(section('Hats', '`src/game/data/hats.ts`.', table(['Id', 'Name'], HATS.map((h) => [h.id, (h as unknown as Row).name ?? h.id]))));
  out.push(section('Celebrations', '`src/game/data/celebrations.ts`.', table(['Id', 'Name'], CELEBRATIONS.map((c) => [c.id, (c as unknown as Row).name ?? c.id]))));
  out.push(section('Themed palettes', '`src/game/data/themedPalettes.ts`.', table(['Id', 'Name'], THEMED_PALETTES.map((p) => [p.id, (p as unknown as Row).name ?? p.id]))));
  const byKind = new Map<string, number>();
  for (const c of CARD_MANIFESTS) byKind.set(String((c as unknown as Row).kind ?? (c as unknown as Row).type ?? 'card'), (byKind.get(String((c as unknown as Row).kind ?? (c as unknown as Row).type ?? 'card')) ?? 0) + 1);
  out.push(section('Cards', 'Collectible card manifests (`src/game/data/cards.ts`). Card art is the procedural rig of the character, enemy, ally or pet, never a raw picture.',
    table(['Kind', 'Count'], [...byKind.entries()].map(([k, n]) => [k, String(n)]))));
  out.push(section('Hub rooms and discoveries', '`src/game/data/progression.ts`.', table(['Id', 'Name', 'Kind'], [
    ...HUB_ROOMS.map((r) => [r.id, (r as unknown as Row).name ?? r.id, 'hub room']),
    ...DISCOVERIES.map((d) => [d.id, (d as unknown as Row).title ?? (d as unknown as Row).name ?? d.id, 'discovery']),
  ])));
  out.push(section('Lok glyph icons', 'Original 24 by 24 facet icons (`src/ui/lokGlyphs.generated.ts`, built by `scripts/build-lok-glyphs.py`). Use `GameIcon` in React or `drawGlyph` on canvas. No emoji and no stock icons.',
    glyphKeys.map((k) => `\`${k}\``).join(', ')));
  out.push(section('Sound cues', 'Gameplay sound cues made by the synth in `src/game/audio/sfxEngine.ts` (no audio files).', cues.map((k) => `\`${k}\``).join(', ')));

  let tracks = '';
  try {
    const cat = JSON.parse(readFileSync(path.join(root, 'public/lok-music-catalog.json'), 'utf8')) as unknown;
    const n = Array.isArray(cat) ? cat.length : Object.values(cat as unknown as Row).reduce<number>((a, v) => a + (Array.isArray(v) ? v.length : 0), 0);
    tracks = `\`public/lok-music-catalog.json\` lists ${n} entries. Local folders in \`public/music/\`: ${files('public/music').length ? files('public/music').join(', ') : readdirSync(path.join(root, 'public/music')).join(', ')}.`;
  } catch { tracks = 'See `public/lok-music-catalog.json` and `public/music/`.'; }
  out.push(section('Music', 'The soundtrack only plays tracks the player owns or the game ships (see `.agents/memory/survivor-616-art-assets.md`).', tracks));

  const pub = files('public');
  const art = files('public/art');
  out.push(section('Pictures and public files', 'The only bitmap pictures. Reference art is only used as a menu backdrop, never shown raw on a character card (see `.agents/memory/survivor-616-art-assets.md`).',
    `**public/art/**\n\n${art.map((f) => `- \`${f}\``).join('\n')}\n\n**public/**\n\n${pub.map((f) => `- \`${f}\``).join('\n')}`));

  const renderDir = path.join(root, 'src/game/render');
  const mods = readdirSync(renderDir).filter((n) => n.endsWith('.ts') && !n.endsWith('.test.ts')).sort();
  const spriteDir = path.join(root, 'src/game/sprites');
  const sprites = readdirSync(spriteDir).filter((n) => n.endsWith('.ts') && !n.endsWith('.test.ts')).sort();
  out.push(section('Renderer and art modules', 'Where each kind of picture is drawn.',
    table(['Module', 'What it draws'], [
      ...mods.map((m) => [`src/game/render/${m}`, purpose(path.join(renderDir, m))]),
      ...sprites.map((m) => [`src/game/sprites/${m}`, purpose(path.join(spriteDir, m))]),
    ])));
  return out.join('\n');
}
