const FALLBACK_BY_TIER: Record<PaletteTier, [PaletteEffectKind, string] | null> = {
  standard: null,
  uncommon: ['glow', 'Soft glow'],
  rare: ['pulse', 'Slow pulse'],
  legendary: ['prism', 'Spectrum'],
};

function effectFor(theme: ThemePalette): PaletteEffectDef | undefined {
  if (theme.variant === 'retro16') {
    return theme.tier === 'standard' ? undefined : { kind: 'static', label: 'CRT scan', speed: 0.9, intensity: 0.4 };
  }
  const picked = EFFECT_BY_BASE[theme.baseId] ?? FALLBACK_BY_TIER[theme.tier];
  if (!picked) return undefined;
  const night = theme.variant === 'midnight';
  const rank = ({ standard: 0, uncommon: 1, rare: 2, legendary: 3 } as const)[theme.tier];
  return { kind: picked[0], label: night ? `${picked[1]}, night shift` : picked[1], speed: 0.5 + rank * 0.12, intensity: Math.min(0.95, 0.45 + rank * 0.14 + (night ? 0.1 : 0)) };
}

function describe(theme: ThemePalette): string {
  if (theme.variant === 'midnight') return `Night-shift remix: ${theme.reference}, flipped for high contrast on a near-black ground.`;
  if (theme.variant === 'retro16') return `Cartridge remix: ${theme.reference}, snapped to 16-bit color for scanline modes.`;
  return `${theme.reference}.`;
}

export function toThemedPalette(theme: ThemePalette): ThemedPaletteDef {
  return {
    id: theme.id,
    name: theme.name,
    description: describe(theme),
    cost: theme.starter ? 0 : COST_BY_TIER[theme.tier],
    owned: theme.starter || undefined,
    tier: theme.tier,
    effect: effectFor(theme),
    palette: toSevenSlot(theme),
    family: theme.group,
    familyLabel: PALETTE_GROUP_LABEL[theme.group],
    variant: theme.variant,
  };
}

/** Base + midnight + retro16 of every registry theme: the unlockable library. */
export const GSIX_REGISTRY_PALETTES: ThemedPaletteDef[] = unlockableLibrary().map(toThemedPalette);
/** The free starter pack, owned from the first launch. */
export const GSIX_STARTER_IDS: string[] = GSIX_REGISTRY_PALETTES.filter((p) => p.owned).map((p) => p.id);
