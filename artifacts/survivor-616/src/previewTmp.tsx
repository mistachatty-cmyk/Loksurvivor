import { CARTRIDGES, type KitGameId } from '@/party/cartridges';
import { CHARACTERS } from '@/game/data/characters';
import '@/index.css';
const q = new URLSearchParams(location.search);
const game = (q.get('g') ?? 'gems') as KitGameId;
const T = Number(q.get('t') ?? 12000);
const cart = CARTRIDGES[game];
const seats = CHARACTERS.slice(0, 4).map((c, i) => ({ characterId: c.id, bot: i !== 0, botSkill: 0.6 }));
const s = cart.create(4, seats);
const cv = document.createElement('canvas');
const view = { w: 600, h: 1170 };
cv.width = 600; cv.height = view.h; cv.style.cssText = 'width:390px;height:760px;display:block;margin:0 auto;background:#000';
document.body.style.margin = '0'; document.body.append(cv);
const fx = new Proxy({}, { get: () => () => {} }) as never;
let clock = 0;
const info = { view, clock: 0, me: 0, calm: false };
for (let t = 0; t < T; t += 1000 / 60) { clock += 1000 / 60; info.clock = clock; cart.step(s, s.runners.map(() => null), 1000 / 60); if (t > T - 700) cart.react(s, fx, info); else cart.react(s, fx, info); if (cart.isOver(s)) break; }
const ctx = cv.getContext('2d')!;
cart.render(ctx, s, info);
cart.hud?.(ctx, s, info);
