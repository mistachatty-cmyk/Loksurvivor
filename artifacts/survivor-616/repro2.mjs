import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args:['--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport: { width: 430, height: 930 }, hasTouch:true });
p.on('pageerror', e => console.log('PAGEERROR', e.message.slice(0,300), (e.stack||'').split('\n').slice(0,5).join(' | ')));
p.on('console', m => { const t=m.text(); if (m.type()==='error' && !/TUNNEL|without an exception/.test(t)) console.log('CONSOLE', t.slice(0,600)); });
const url = process.argv[2];
await p.goto(url, { waitUntil: 'networkidle' });
await p.waitForTimeout(1500);
const bad = async (tag) => console.log(tag, (await p.evaluate(() => document.body.innerText)).includes('SOMETHING WENT WRONG') ? 'CRASHED' : 'ok', await p.evaluate(()=>document.querySelector('[data-testid=screen-jukebox-room]')?.dataset.theaterLevel));
await bad('load');
await p.mouse.click(215, 400); await p.waitForTimeout(1500); await bad('after tap');
await p.waitForTimeout(5000); await bad('5s');
await p.screenshot({ path: '/tmp/j5.png' });
await p.waitForTimeout(21000); await bad('26s');
await p.mouse.click(215, 400); await p.waitForTimeout(800); await bad('wake');
await b.close();
