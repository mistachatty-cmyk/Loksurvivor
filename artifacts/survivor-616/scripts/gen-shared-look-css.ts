// Writes the menu-theme CSS for the looks shared with Queens N Kings into src/index.css, between the two marker lines.
// Run from artifacts/survivor-616: pnpm exec tsx scripts/gen-shared-look-css.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { SHARED_LOOKS, sharedLookCssVars, hexToHsl } from '../../../lib/lok-universe/src/sharedLooks';

const BEGIN = '/* BEGIN shared Lok looks (generated by scripts/gen-shared-look-css.ts) */', END = '/* END shared Lok looks */';
const lines = [BEGIN];
for (const l of SHARED_LOOKS) {
  const id = `lok-${l.id}`;
  lines.push(`[data-ui-theme='${id}'] { ${Object.entries(sharedLookCssVars(l)).map(([k, v]) => `${k}: ${v};`).join(' ')} }`);
  for (const [suffix, hex] of [['pale', l.accent2], ['glow', l.glow]] as const) { const hsl = hexToHsl(hex); lines.push(`[data-ui-theme='${id}'][data-ui-swatch='${id}-${suffix}'] { --primary: ${hsl}; --ring: ${hsl}; }`); }
}
lines.push(END);
const path = new URL('../src/index.css', import.meta.url).pathname;
let css = readFileSync(path, 'utf8');
const a = css.indexOf(BEGIN), b = css.indexOf(END);
if (a >= 0 && b > a) css = css.slice(0, a) + lines.join('\n') + css.slice(b + END.length);
else { const m = css.indexOf("[data-ui-theme='glimmerwild'][data-ui-swatch='moon-cream']"); const eol = css.indexOf('\n', m); css = css.slice(0, eol + 1) + lines.join('\n') + '\n' + css.slice(eol + 1); }
writeFileSync(path, css);
console.log(`wrote ${SHARED_LOOKS.length} looks`);
