/**
 * The ecosystem status report: which apps exist in the repo, which plugins each one switches on, and whether
 * their manifests are sound. Pure: it takes the manifests as data so a test can feed it fixtures; the CLI reads
 * the files. Output is Markdown for `docs/ECOSYSTEM_STATUS.md`.
 */
import { checkManifest } from './manifest';

export interface AppManifest { path: string; manifest: unknown }

export interface AppStatus {
  path: string;
  appKey: string;
  label: string;
  sdkVersion: string;
  problems: string[];
  plugins: Array<{ block: string; enabled: boolean; detail?: string }>;
}

const isObject = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);

export function appStatus(app: AppManifest): AppStatus {
  const m = isObject(app.manifest) ? app.manifest : {};
  const plugins: AppStatus['plugins'] = [];
  const chat = isObject(m.lokChat) ? m.lokChat : undefined;
  const crash = isObject(m.lokErrorReport) ? m.lokErrorReport : undefined;
  if (crash) plugins.push({ block: 'lokErrorReport', enabled: crash.enabled === true });
  if (chat) {
    const off = isObject(chat.features) ? Object.entries(chat.features).filter(([, v]) => v === false).map(([k]) => k) : [];
    plugins.push({ block: 'lokChat', enabled: chat.enabled === true, detail: off.length > 0 ? `off: ${off.join(', ')}` : undefined });
  }
  if (m.supporterBar) plugins.push({ block: 'supporterBar', enabled: true });
  if (m.walletStrip) plugins.push({ block: 'walletStrip', enabled: true });
  if (m.publicLore) plugins.push({ block: 'publicLore', enabled: true });
  return {
    path: app.path,
    appKey: String(m.appKey ?? '?'),
    label: String(m.label ?? '?'),
    sdkVersion: String(m.sdkVersion ?? '?'),
    problems: checkManifest(app.manifest),
    plugins,
  };
}

export function renderStatus(apps: readonly AppStatus[], latestSdk: string): string {
  const out = ['# LOK ecosystem status', '', 'Generated by `pnpm lok:status` (packages/lok-ecosystem). Do not edit by hand.', ''];
  out.push(`SDK in this repo: **${latestSdk}**. Apps: **${apps.length}**.`, '');
  out.push('| App | Key | SDK | Plugins on | Manifest |', '| --- | --- | --- | --- | --- |');
  for (const a of apps) {
    const on = a.plugins.filter((p) => p.enabled).map((p) => (p.detail ? `${p.block} (${p.detail})` : p.block)).join(', ') || 'none';
    const sdk = a.sdkVersion === latestSdk ? a.sdkVersion : `${a.sdkVersion} (latest ${latestSdk})`;
    out.push(`| ${a.label} | \`${a.appKey}\` | ${sdk} | ${on} | ${a.problems.length === 0 ? 'ok' : `${a.problems.length} problem(s)`} |`);
  }
  const broken = apps.filter((a) => a.problems.length > 0);
  if (broken.length > 0) {
    out.push('', '## Problems', '');
    for (const a of broken) { out.push(`### ${a.label} (\`${a.path}\`)`, ''); for (const p of a.problems) out.push(`- ${p}`); out.push(''); }
  }
  out.push('');
  return out.join('\n');
}
